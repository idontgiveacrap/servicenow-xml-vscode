/**
 * Regenerate src/kinds/scriptFields.generated.ts from a sys_dictionary CSV export.
 *
 *   node scripts/pack-script-fields.js "path/to/sys_dictionary.csv"
 *
 * Export the list from an instance with:
 *   /sys_dictionary_list.do?sysparm_query=internal_typeSTARTSWITHscript&CSV
 *     &sysparm_default_export_fields=all
 *
 * Required columns: name (table), element (field), internal_type.
 */

const fs = require('fs');
const path = require('path');

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '"') {
      if (inQuotes && text[i + 1] === '"') {
        cur += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }
    if (!inQuotes && ch === ',') {
      row.push(cur);
      cur = '';
      continue;
    }
    if (!inQuotes && (ch === '\n' || ch === '\r')) {
      if (ch === '\r' && text[i + 1] === '\n') {
        i++;
      }
      row.push(cur);
      rows.push(row);
      row = [];
      cur = '';
      continue;
    }
    cur += ch;
  }
  if (cur !== '' || row.length > 0) {
    row.push(cur);
    rows.push(row);
  }
  return rows;
}

const csvPath = process.argv[2];
if (!csvPath) {
  console.error('usage: node scripts/pack-script-fields.js <sys_dictionary.csv>');
  process.exit(1);
}

const rows = parseCsv(fs.readFileSync(csvPath, 'utf8'));
const header = rows[0].map((h) => h.trim());
const iTable = header.indexOf('name');
const iElement = header.indexOf('element');
const iType = header.indexOf('internal_type');
if (iTable < 0 || iElement < 0 || iType < 0) {
  console.error('CSV must have name, element, and internal_type columns');
  process.exit(1);
}

const pairs = new Set();
const elements = new Set();
const clientPairs = new Set();

for (const row of rows.slice(1)) {
  if (row.length <= iType) {
    continue;
  }
  const table = row[iTable].trim();
  const element = row[iElement].trim();
  const type = row[iType].trim();
  if (!table || !element || !/^script/i.test(type)) {
    continue;
  }
  pairs.add(`${table}.${element}`);
  elements.add(element);
  if (/client/i.test(type)) {
    clientPairs.add(`${table}.${element}`);
  }
}

const quote = (values) =>
  [...values]
    .sort()
    .map((v) => `  ${JSON.stringify(v)}`)
    .join(',\n');

const out = `// Generated by scripts/pack-script-fields.js — do not edit by hand.
// Source: sys_dictionary rows whose internal_type starts with "script".
// ${pairs.size} table.field pairs over ${elements.size} distinct field names.

/**
 * Script-typed fields keyed as \`table.field\`.
 *
 * Keyed by pair rather than field name because the same name is code on one
 * table and data on another: \`value\` is a script on some tables and an integer
 * on sys_properties, and \`layout\` is a script on some tables and JSON on the
 * sys_ux_* ones.
 */
export const SCRIPT_FIELD_PAIRS: ReadonlySet<string> = new Set([
${quote(pairs)}
]);

/**
 * Every field name that is script-typed on at least one table. Used only as a
 * fallback for records whose table is absent from the dictionary export, so it
 * deliberately excludes names that are too generic to guess from.
 */
export const SCRIPT_FIELD_ELEMENTS: ReadonlySet<string> = new Set([
${quote(elements)}
]);

/** Pairs whose dictionary type is explicitly client-side. */
export const CLIENT_SCRIPT_FIELD_PAIRS: ReadonlySet<string> = new Set([
${quote(clientPairs)}
]);
`;

const target = path.join(__dirname, '..', 'src', 'kinds', 'scriptFields.generated.ts');
fs.writeFileSync(target, out, 'utf8');
console.log(
  `wrote ${path.relative(path.join(__dirname, '..'), target)}: ` +
    `${pairs.size} pairs, ${elements.size} field names, ${clientPairs.size} client pairs`
);
